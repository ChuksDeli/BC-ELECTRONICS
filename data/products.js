export function getProductById(id) {
  return products.find((p) => p.id === id);
}

export function getProductsByCategory(categoryId) {
  return products.filter((p) => p.category === categoryId);
}

export function getRelatedProducts(product, count = 4) {
  return products
    .filter((p) => p.category === product.category && p.id !== product.id)
    .slice(0, count);
}

export function getFlashSaleProducts() {
  return products.filter((p) => p.isFlashSale);
}

export function getNewArrivals() {
  return products.filter((p) => p.isNew);
}

export function getBestSellers() {
  return products.filter((p) => p.isBestSeller);
}

export function getTrendingProducts(count = 8) {
  return [...products].sort((a, b) => b.reviews - a.reviews).slice(0, count);
}

export function searchProducts(query) {
  const q = query.toLowerCase();
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.brand.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q)
  );
}